// Compiles contracts/ZozaLaunchpad.sol and writes the factory's ABI and
// creation bytecode to lib/launchpad-artifact.ts, which the /deploy page uses.
//
//   npm i --no-save solc@0.8.24 && node scripts/compile-contracts.cjs
const fs = require("fs");
const path = require("path");
const solc = require("solc");

const root = path.join(__dirname, "..");
const source = fs.readFileSync(path.join(root, "contracts/ZozaLaunchpad.sol"), "utf8");
const input = {
  language: "Solidity",
  sources: { "ZozaLaunchpad.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    viaIR: true,
    evmVersion: "paris",
    outputSelection: { "*": { ZozaLaunchFactory: ["abi", "evm.bytecode.object"] } },
  },
};
const out = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (out.errors || []).filter((e) => e.severity === "error");
if (errors.length) {
  errors.forEach((e) => console.error(e.formattedMessage));
  process.exit(1);
}
const factory = out.contracts["ZozaLaunchpad.sol"].ZozaLaunchFactory;
const ctor = factory.abi.filter((x) => x.type === "constructor" || (x.type === "function" && ["owner", "treasury", "launchFee", "feeEscrow", "tokenCount"].includes(x.name)));
const file = `// Generated by scripts/compile-contracts.cjs from contracts/ZozaLaunchpad.sol
// (solc ${solc.version()}, optimizer 200 runs, viaIR, evm paris). Do not edit.
export const FACTORY_ABI = ${JSON.stringify(ctor)} as const;

export const FACTORY_BYTECODE = "0x${factory.evm.bytecode.object}" as const;
`;
fs.writeFileSync(path.join(root, "lib/launchpad-artifact.ts"), file);
console.log(`lib/launchpad-artifact.ts written (${factory.evm.bytecode.object.length / 2} bytes of init code)`);
